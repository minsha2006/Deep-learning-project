      "\n",
      "1. The function calls itself with a smaller value of `n` (i.e., `n-1`) until it reaches the base case (`n == 1`).\n",
      "2. At each recursive call, the function multiplies the current value of `n` with the result of the recursive call.\n",
      "3. The recursion continues until the base case is reached, at which point the function returns the final result.\n",
