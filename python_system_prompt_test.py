      "\n",
      "Now, let's implement the same function using a recursive approach:\n",
      "```python\n",
      "def factorial_recursive(n):\n",
      "    # Base case: 1! = 1\n",
      "    if n == 1:\n",
      "        return 1\n",
      "    # Recursive case: n! = n * (n-1)!\n",
      "    else:\n",
      "        return n * factorial_recursive(n - 1)\n",
      "```\n",
